// Минимальный Lexical JSON: заголовки, абзацы и списки
const text = (t: string) => ({
  type: 'text',
  text: t,
  version: 1,
  format: 0,
  detail: 0,
  mode: 'normal',
  style: '',
})
const node = (type: string, children: unknown[], extra: Record<string, unknown> = {}) => ({
  type,
  children,
  version: 1,
  direction: 'ltr',
  format: '',
  indent: 0,
  ...extra,
})

export function toLexical(blocks: Block[]): SerializedEditorState {
  const children = blocks.map((b) => {
    if ('h' in b) return node('heading', [text(b.h)], { tag: 'h2' })
    if ('p' in b) return node('paragraph', [text(b.p)], { textFormat: 0, textStyle: '' })
    const ordered = 'ol' in b
    const items = ordered ? b.ol : b.ul
    return node(
      'list',
      items.map((it, i) => node('listitem', [text(it)], { value: i + 1 })),
      { listType: ordered ? 'number' : 'bullet', tag: ordered ? 'ol' : 'ul', start: 1 },
    )
  })
  return { root: node('root', children) } as unknown as SerializedEditorState
}
